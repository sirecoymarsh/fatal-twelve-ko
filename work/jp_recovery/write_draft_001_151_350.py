def main() -> int:
    payload = json.loads(PACKET.read_text(encoding="utf-8", errors="strict"))
    entries = payload["entries"]
    assert len(entries) == 200
    assert {entry["sequence"] for entry in entries} == set(range(151, 351))
    assert set(TRANSLATIONS) == set(range(151, 351))

    for entry in entries:
        entry["draft_ko"] = TRANSLATIONS[entry["sequence"]]
        entry["status"] = "first_draft_unreviewed"
        entry["qa"] = "deferred"

    output = {
        "packet_id": "scenario_001_151_350",
        "sequence_start": 151,
        "sequence_end": 350,
        "entry_count": 200,
        "source_language": "Japanese",
        "target_language": "Korean",
        "translation_basis": "Japanese source, speaker, and scene context only",
        "translation_id_usage": "technical identification only",
        "english_reference_used": False,
        "status": "first_draft_unreviewed",
        "qa": "deferred",
        "entries": entries,
    }
    JSON_OUTPUT.write_text(
        json.dumps(output, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

    lines = [
        "# Fatal Twelve Korean first draft: scenario/001 sequence 151-350",
        "# Semantic source: Japanese only. Translation IDs are technical keys only.",
        "# Status: first_draft_unreviewed; QA deferred.",
        "",
    ]
    for entry in entries:
        lines.append(f"translate korean {entry['translation_id']}:")
        lines.append("")
        if entry["voice_call"]:
            lines.append(f"    {entry['voice_call']}")
            lines.append("")
        speaker = "" if entry["speaker"] == "narrator" else entry["speaker"] + " "
        rendered = json.dumps(entry["draft_ko"], ensure_ascii=False)
