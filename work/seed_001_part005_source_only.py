    out.parent.mkdir(parents=True, exist_ok=True)
    records = []
    for sequence, source_line, speaker, source_jp, draft_ko in ENTRIES:
        records.append({
            "stable_id": f"scenario/001.rpy::L{source_line}",
            "sequence": sequence,
            "translation_id": None,
            "translation_id_status": "pending_ast_alignment",
            "source_file": "scenario/001.rpy",
            "source_line": source_line,
            "speaker": speaker,
            "source_jp": source_jp,
            "draft_ko": draft_ko,
            "source_authority": "Japanese only",
            "english_reference_used": False,
            "status": "first_draft_unreviewed",
            "qa": "deferred_until_full_first_draft",
        })
    payload = {
        "packet_id": "scenario_001_part005_source_only",
        "source_language": "Japanese",
        "target_language": "Korean",
        "entry_count": len(records),
        "translation_id_alignment": "pending; do not use naive sequence alignment across Ren'Py menu/string blocks",
        "status": "first_draft_unreviewed",
        "qa_policy": "No translation QA until the complete first draft is finished; review once afterward.",
        "english_text_in_translator_packet": False,
        "entries": records,
    }
